#!/usr/bin/env node
/**
 * Validate built Next.js CSS before Vercel promotes a deployment.
 *
 * This runs after `next build` and fails the build if the generated CSS is
 * missing critical Tailwind utilities. That prevents a Vercel Git build from
 * becoming production when CSS compilation silently drops layout classes.
 */

const fs = require('fs');
const path = require('path');

const chunksDir = path.join(process.cwd(), '.next', 'static', 'chunks');
const requiredUtilities = [
  '.w-full',
  '.h-11',
  '.max-w-sm',
  '.rounded-2xl',
  '.justify-between',
  '.items-center',
];

if (!fs.existsSync(chunksDir)) {
  console.error(`❌ Built CSS chunks directory not found: ${chunksDir}`);
  process.exit(1);
}

const cssFiles = fs.readdirSync(chunksDir)
  .filter((name) => name.endsWith('.css'))
  .map((name) => path.join(chunksDir, name));

if (cssFiles.length === 0) {
  console.error('❌ No CSS chunks generated by Next.js build');
  process.exit(1);
}

const combinedCss = cssFiles.map((file) => fs.readFileSync(file, 'utf8')).join('\n');
const missing = requiredUtilities.filter((utility) => !combinedCss.includes(utility));

console.log(`Built CSS validation: scanned ${cssFiles.length} CSS chunk(s)`);
for (const file of cssFiles) {
  const size = fs.statSync(file).size;
  console.log(`- ${path.relative(process.cwd(), file)} (${size} bytes)`);
}

if (missing.length > 0) {
  console.error(`❌ Built CSS is missing critical Tailwind utilities: ${missing.join(', ')}`);
  process.exit(1);
}

console.log('✅ Built CSS contains critical Tailwind utilities');
